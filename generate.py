#!/usr/bin/env python3
"""
generate.py — turn spec.py into the artifacts the v2 benchmarks and RTL use.

Emits (all derived from spec.py, so nothing can silently drift):
  vectors.txt        golden (nonce, digest, difficulty_value, raw-state) tuples
  cpu/tables.h       epoch tables + params for the v2 C benchmark
  fpga/ring.v        the v2 ring core (one LUT4 per cell, NDSP DSP48 products)
  fpga/tb_vectors.v  iverilog testbench: run the core, check it matches spec

Run:  python3 generate.py     (pure-python vectors: allow several minutes)
"""
import spec
from spec import B, W, DEPTH, ADDR, STEPS, NDSP, EPOCH

RULE, TAP, (MULA, MULB, MULC), ADDR_BITS = spec.epoch_tables(EPOCH)
# First three unchanged since v2 (existing vectors stay byte-identical);
# the rest exercise the full 64-bit nonce width and dense/sparse patterns.
NONCES = [0, 1, 0xdeadbeef,
          0xffffffffffffffff, 0x8000000000000000, 0x0123456789abcdef,
          0x5555555555555555, 0x00000000ffffffff]
PREVCHUNK = [sum(((spec.PREV >> ((b*W + c) % 256)) & 1) << c for c in range(W)) for b in range(B)]

def hx(v, nbits): return f"{v:0{(nbits+3)//4}x}"

# ---------- cpu/tables.h ----------
with open("cpu/tables.h", "w") as f:
    f.write("/* generated by generate.py from spec.py -- do not edit */\n")
    f.write(f"#define B {B}\n#define W {W}\n#define DEPTH {DEPTH}\n")
    f.write(f"#define ADDRB {ADDR}\n#define STEPS {STEPS}\n#define NDSP {NDSP}\n")
    f.write(f"#define EPOCH_CONST 0x{spec.epoch_const(EPOCH):016x}ULL\n")
    f.write(f"static const unsigned short RULE[{len(RULE)}]={{"+",".join(f"0x{r:04x}" for r in RULE)+"};\n")
    f.write(f"static const unsigned char  TAPK[{len(TAP)}]={{"+",".join(str(t[0]) for t in TAP)+"};\n")
    f.write(f"static const unsigned short TAPX[{len(TAP)}]={{"+",".join(str(t[1]) for t in TAP)+"};\n")
    f.write(f"static const unsigned char  TAPY[{len(TAP)}]={{"+",".join(str(t[2]) for t in TAP)+"};\n")
    f.write(f"static const unsigned short MULA[{NDSP}]={{"+",".join(map(str, MULA))+"};\n")
    f.write(f"static const unsigned short MULB[{NDSP}]={{"+",".join(map(str, MULB))+"};\n")
    f.write(f"static const unsigned int   MULC[{NDSP}]={{"+",".join(f"0x{c:08x}u" for c in MULC)+"};\n")
    flat = [p for bits in ADDR_BITS for p in bits]
    f.write(f"static const unsigned char  ADDRBIT[{len(flat)}]={{"+",".join(str(p) for p in flat)+"};\n")
    f.write(f"static const unsigned int   PREVCHUNK[{B}]={{"+",".join(str(p) for p in PREVCHUNK)+"};\n")

# ---------- fpga/ring.v ----------
NB = B * W
L = [f"// generated by generate.py from spec.py",
     f"// BRAM-ring v2 core: B={B} lanes, W={W}, DEPTH={DEPTH} (full RAM10), STEPS={STEPS},",
     f"// NDSP={NDSP} DSP products. Same EFX_RAM10-primitive rationale as ring.v (independent",
     f"// WADDR/RADDR ports; READ_FIRST gives the RMW its old value) -- now using all 512 rows.",
     f"// The FILL phase runs the SAME CA+DSP datapath as RUN (spec change #4): write",
     f"// address is the row counter, RAM read is masked to zero. One datapath, no",
     f"// per-lane fill generator, no write-data mux, no read-address mux.",
     f"// Each product ma*mb+C is one DSP48 (18x19 multiplier + post-adder) with",
     f"// OPERAND AND OUTPUT REGISTERS (v3 respec, 2026-08-04): taps read the",
     f"// products of the ring state TWO steps back (zero for steps 0,1 -- IDLE +",
     f"// delayed clear). The 2-step skew gives the globally-routed operands a",
     f"// full cycle and keeps the DSP layer off the critical path (Topaz C3:",
     f"// 161 MHz combinational, 212 at 1-step lag operand-route-bound, vs 222",
     f"// with no DSP layer at all).",
     f"// The FSM (st/cnt) is REPLICATED per {64}-lane group (syn_keep) so the",
     f"// fill-select/WE/rden broadcast to {B} RAMs is local, not one global cone",
     f"// (Topaz probe: cnt->WADDR was the post-DSP critical path).",
     f"// state_in is latched in the single IDLE->FILL cycle (the miner may reuse its",
     f"// seed shadow register immediately afterwards).",
     f"module ring (input wire clk, input wire rst_n, input wire start,",
     f"              input wire [{NB-1}:0] state_in, output reg done,",
     f"              output wire [{NB-1}:0] state_out);",
     f"  localparam integer STEPS={STEPS};",
     f"  reg [{W-1}:0] head [0:{B-1}];",
     f"  localparam IDLE=0,FILL=1,RUN=2,FIN=3;",
     f"  reg [1:0] st; reg [15:0] cnt;"]
GS = 64; NG = B // GS
for g in range(NG):
    L += [f"  (* syn_keep = 1 *) reg [1:0] str{g}; (* syn_keep = 1 *) reg [15:0] cntr{g};",
          f"  always @(posedge clk or negedge rst_n) begin",
          f"    if(!rst_n) begin str{g}<=IDLE; cntr{g}<=16'd0; end else case(str{g})",
          f"      IDLE: if(start) begin str{g}<=FILL; cntr{g}<=16'd0; end",
          f"      FILL: if(cntr{g}=={DEPTH-1}) begin str{g}<=RUN; cntr{g}<=16'd0; end else cntr{g}<=cntr{g}+1'b1;",
          f"      RUN:  begin cntr{g}<=cntr{g}+1'b1; if(cntr{g}==STEPS-1) str{g}<=FIN; end",
          f"      FIN:  if(!start) str{g}<=IDLE;",
          f"    endcase",
          f"  end",
          f"  wire rden{g} = (str{g}==RUN && cntr{g}!=16'd0);   // RAM read joins from the 2nd RUN step"]
L.append("  reg pclr;   // 1-cycle-delayed IDLE clear: p stays zero for steps 0 AND 1 (spec 2-step lag)")
for j in range(NDSP):
    L.append(f"  reg [17:0] ra{j}; reg [18:0] rb{j}; reg [37:0] p{j};   // DSP operand + output regs")
L.append("  always @(posedge clk) begin   // registered DSP products, TWO deep (spec: 2-step lag)")
L.append("    pclr <= (st==IDLE);")
for j in range(NDSP):
    L.append(f"    ra{j} <= head[{MULA[j]}][17:0]; rb{j} <= {{head[{MULB[j]}][17:0],1'b1}};")
    L.append(f"    p{j} <= (st==IDLE || pclr) ? 38'd0 : ra{j}*rb{j} + 38'h{MULC[j]:x};")
L.append("  end")
for b in range(B):
    L.append(f"  wire [{W-1}:0] rdh{b};")
for b in range(B):
    L.append(f"  wire [{W-1}:0] u{b} = head[{b}] ^ (rden{b//GS} ? rdh{b} : {W}'d0);")
    L.append(f"  wire [{W-1}:0] g{b};")
    for c in range(W):
        l=(c-1)%W; ri=(c+1)%W; k,tx,ty=TAP[b*W+c]; tt=RULE[b*W+c]
        tap = f"p{tx}[{ty}]" if k else f"head[{tx}][{ty}]"
        L.append(f"  assign g{b}[{c}] = 16'h{tt:04x} >> {{{tap},u{b}[{ri}],u{b}[{c}],u{b}[{l}]}};")
    L.append(f"  wire [{W-1}:0] v{b} = g{b};")
    ab = ADDR_BITS[b]
    L.append(f"  wire [{ADDR-1}:0] addr{b} = {{"+",".join(f"v{b}[{ab[k]}]" for k in range(ADDR-1,-1,-1))+"};")
L += ["  always @(posedge clk or negedge rst_n) begin",
      "    if(!rst_n) begin st<=IDLE; done<=1'b0; cnt<=16'd0; end else case(st)",
      "      IDLE: if(start) begin st<=FILL; cnt<=16'd0; done<=1'b0; end",
      f"      FILL: if(cnt=={DEPTH-1}) begin st<=RUN; cnt<=16'd0; end else cnt<=cnt+1'b1;",
      "      RUN:  begin cnt<=cnt+1'b1; if(cnt==STEPS-1) st<=FIN; end",
      "      FIN:  begin done<=1'b1; if(!start) st<=IDLE; end",
      "    endcase",
      "  end",
      "  always @(posedge clk) begin"]
for b in range(B):
    src=(b-1)%B; g=b//GS
    L.append(f"    if(str{g}==IDLE && start) head[{b}]<=state_in[{b*W} +: {W}];"
             f" else if(str{g}==FILL || str{g}==RUN) head[{b}]<=v{src};")
L.append("  end")
for b in range(B):
    L += [f"  EFX_RAM10 #(.READ_WIDTH({W}), .WRITE_WIDTH({W}), .OUTPUT_REG(1'b0), .WRITE_MODE(\"READ_FIRST\"),",
          f"    .WE_POLARITY(2'b11), .WCLKE_POLARITY(1'b1), .WADDREN_POLARITY(1'b1), .RADDREN_POLARITY(1'b1),",
          f"    .RE_POLARITY(1'b1), .RESET_RAM(\"NONE\"), .RESET_OUTREG(\"NONE\"))",
          f"    u_ram{b} (.WCLK(clk), .RCLK(clk), .WCLKE(1'b1), .WADDREN(1'b1), .RADDREN(1'b1), .RST(1'b0),",
          f"      .WE({{2{{str{b//GS}==FILL || str{b//GS}==RUN}}}}), .WADDR((str{b//GS}==FILL)?cntr{b//GS}[{ADDR-1}:0]:addr{b}), .WDATA(v{b}),",
          f"      .RE(str{b//GS}==RUN), .RADDR(addr{b}), .RDATA(rdh{b}));"]
L.append("  assign state_out={"+",".join(f"head[{b}]" for b in range(B-1,-1,-1))+"};")
L.append("endmodule")
open("fpga/ring.v", "w").write("\n".join(L) + "\n")
print(f"wrote cpu/tables.h, fpga/ring.v  ({B} lanes x {W} cells, {B} RAM10 blocks, {NDSP} DSPs)")

# ---------- miner includes (same roles as generate.py's epoch/params/prev) ----------
open("fpga/epoch.vh", "w").write(
    f"// generated by generate.py\n`define EPOCH_CONST 64'h{spec.epoch_const(EPOCH):016x}\n")
open("fpga/params.vh", "w").write(
    f"// generated by generate.py — keep miner.v in sync with spec.py\n"
    f"`define RING_B {B}\n`define RING_W {W}\n")
# miner.v regenerates PREVCHUNK[b] on the fly from a 256-bit rotating register
# (PREVCHUNK[b] is just PREV rotated by b*W, low W bits), so only the raw 256-bit
# PREV constant is baked -- 256 FFs instead of v1's B*W-bit rotating register.
# Requires (B*W) % 256 == 0 so the rotator self-restores after a seeding pass.
assert (B * W) % 256 == 0, "miner.v PREV rotator needs B*W divisible by 256"
open("fpga/prev256.vh", "w").write(
    f"// generated by generate.py — raw 256-bit PREV (see miner.v)\n"
    f"localparam [255:0] PREV256 = 256'h{spec.PREV:064x};\n")
print("wrote fpga/{epoch.vh,params.vh,prev256.vh}")

# ---------- vectors.txt (pure-python golden runs -- the slow part) ----------
import sys, time
runs = {}
with open("vectors.txt", "w") as f:
    f.write(f"# BRAM-ring v2 golden vectors  (epoch={EPOCH}  B={B} W={W} DEPTH={DEPTH} STEPS={STEPS} NDSP={NDSP})\n")
    f.write("# nonce  sha256_digest  difficulty_value  raw_state(hex, lane B-1..0)\n")
    for n in NONCES:
        t0 = time.time()
        heads = spec.run(EPOCH, n)
        runs[n] = heads
        raw = "".join(hx(heads[b], W) for b in range(B - 1, -1, -1))
        import hashlib as _h
        dig = _h.sha256(spec.pack(heads)).hexdigest()
        f.write(f"{n:016x} {dig} {spec.difficulty_value(heads):08x} {raw}\n")
        f.flush()
        print(f"  vector nonce={n:#x} done in {time.time()-t0:.0f}s", flush=True)

# ---------- fpga/tb_vectors.v (checks EVERY vector, full reset between runs) ----------
NV = len(NONCES)
sin_init  = "\n".join(
    f"    SINV[{i}]  = {NB}'h" + "".join(hx(spec.init_heads(EPOCH, n)[b], W) for b in range(B-1, -1, -1)) + ";"
    for i, n in enumerate(NONCES))
sexp_init = "\n".join(
    f"    SEXPV[{i}] = {NB}'h" + "".join(hx(runs[n][b], W) for b in range(B-1, -1, -1)) + ";"
    for i, n in enumerate(NONCES))
nonce_list = ", ".join(f"{n:#x}" for n in NONCES)
open("fpga/tb_vectors.v", "w").write(f"""// generated by generate.py -- checks ring.v against spec for all {NV} golden
// vectors (nonces {nonce_list}), with a full reset between runs.
`timescale 1ns/1ps
module tb;
  reg clk=0,rst_n=0,start=0; reg [{NB-1}:0] sin; wire [{NB-1}:0] sout; wire done;
  reg [{NB-1}:0] SINV [0:{NV-1}]; reg [{NB-1}:0] SEXPV [0:{NV-1}];
  ring dut(.clk(clk),.rst_n(rst_n),.start(start),.state_in(sin),.done(done),.state_out(sout));
  always #5 clk=~clk; integer cyc=0; integer v;
  initial begin
{sin_init}
{sexp_init}
    for (v = 0; v < {NV}; v = v + 1) begin
      rst_n=0; start=0; sin=SINV[v]; #12 rst_n=1; #10 start=1; cyc=0;
      while(!done) begin @(posedge clk); cyc=cyc+1;
        if(cyc>{STEPS+DEPTH+80}) begin $display("FAIL: TIMEOUT — ring.v never asserted done (vector %0d)", v); $fatal(1); end end
      #1; if(sout==SEXPV[v]) $display("PASS: ring.v == spec.py, vector %0d (%0d cycles/hash)", v, cyc);
          else begin $display("FAIL: ring.v != spec.py, vector %0d", v); $fatal(1); end
      start=0; #20;
    end
    $display("PASS: ring.v == spec.py on all {NV} golden vectors");
    $finish; end
endmodule
""")
print("wrote vectors.txt, fpga/tb_vectors.v")
